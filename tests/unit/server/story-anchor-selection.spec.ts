// @vitest-environment node
import { describe, expect, it } from 'vitest'
import { selectKeyframeProvider } from '../../../server/story/anchor-selection'

const ANCHOR_A = 'https://v3.fal.media/files/a.jpg'
const ANCHOR_B = 'https://v3.fal.media/files/b.jpg'

describe('keyframe provider selection', () => {
  it('uses FLUX when nothing is anchored', () => {
    expect(selectKeyframeProvider({
      userReferenceUrl: null,
      presentCharacterIds: ['clara'],
      anchors: {},
    })).toEqual({ kind: 'flux' })
  })

  it('uses Kontext with one anchor', () => {
    expect(selectKeyframeProvider({
      userReferenceUrl: null,
      presentCharacterIds: ['clara'],
      anchors: { clara: ANCHOR_A },
    })).toEqual({ kind: 'kontext', referenceUrl: ANCHOR_A })
  })

  it('uses Kontext multi with two anchors', () => {
    expect(selectKeyframeProvider({
      userReferenceUrl: null,
      presentCharacterIds: ['clara', 'rival'],
      anchors: { clara: ANCHOR_A, rival: ANCHOR_B },
    })).toEqual({ kind: 'kontext-multi', referenceUrls: [ANCHOR_A, ANCHOR_B] })
  })

  it('ignores characters that are not present or not anchored', () => {
    expect(selectKeyframeProvider({
      userReferenceUrl: null,
      presentCharacterIds: ['clara'],
      anchors: { clara: ANCHOR_A, rival: ANCHOR_B },
    })).toEqual({ kind: 'kontext', referenceUrl: ANCHOR_A })

    expect(selectKeyframeProvider({
      userReferenceUrl: null,
      presentCharacterIds: ['clara', 'rival'],
      anchors: { clara: ANCHOR_A },
    })).toEqual({ kind: 'kontext', referenceUrl: ANCHOR_A })
  })

  it('lets the user reference win and dedupes character ids', () => {
    const reference = 'https://v3.fal.media/files/user.jpg'

    // The uploaded image already carries face and style, so it is the only
    // reference and Nano Banana keeps both better than Kontext.
    expect(selectKeyframeProvider({
      userReferenceUrl: reference,
      presentCharacterIds: ['clara', 'clara'],
      anchors: { clara: ANCHOR_A },
    })).toEqual({ kind: 'nano-banana', referenceUrls: [reference] })

    expect(selectKeyframeProvider({
      userReferenceUrl: null,
      presentCharacterIds: ['clara', 'clara', 'rival'],
      anchors: { clara: ANCHOR_A, rival: ANCHOR_B },
    })).toEqual({ kind: 'kontext-multi', referenceUrls: [ANCHOR_A, ANCHOR_B] })
  })
})

describe('first keyframe must seed the anchor with FLUX', () => {
  // Mirrors the orchestrator rule: a scene with any un-anchored character is
  // generated by FLUX so the anchor is always 1152x2048 and vertical.
  function providerFor(anchors: Record<string, string>, characters: string[]) {
    const needsSeed = characters.some((id) => anchors[id] === undefined)

    return needsSeed
      ? { kind: 'flux' as const }
      : selectKeyframeProvider({
          userReferenceUrl: null,
          presentCharacterIds: characters,
          anchors,
        })
  }

  it('seeds with FLUX while any character has no anchor', () => {
    expect(providerFor({}, ['clara'])).toEqual({ kind: 'flux' })
    expect(providerFor({ clara: ANCHOR_A }, ['clara', 'rival'])).toEqual({ kind: 'flux' })
  })

  it('uses Kontext once every character is anchored', () => {
    expect(providerFor({ clara: ANCHOR_A }, ['clara']))
      .toEqual({ kind: 'kontext', referenceUrl: ANCHOR_A })
    expect(providerFor({ clara: ANCHOR_A, rival: ANCHOR_B }, ['clara', 'rival']))
      .toEqual({ kind: 'kontext-multi', referenceUrls: [ANCHOR_A, ANCHOR_B] })
  })
})

describe('character sheet priority', () => {
  it('sends the user image instead of the sheet when both exist', () => {
    const reference = 'https://v3.fal.media/files/user.jpg'
    const provider = selectKeyframeProvider({
      characterSheet: [ANCHOR_A],
      sheetFallback: [ANCHOR_A],
      userReferenceUrl: reference,
      presentCharacterIds: ['clara'],
      anchors: { clara: ANCHOR_A },
      preferred: 'nano-banana',
    })

    expect(provider).toEqual({ kind: 'nano-banana', referenceUrls: [reference] })
  })

  it('uses the stored sheet as a fallback when there is no uploaded image', () => {
    const provider = selectKeyframeProvider({
      userReferenceUrl: null,
      sheetFallback: [ANCHOR_A, ANCHOR_B, ANCHOR_A, ANCHOR_B],
      presentCharacterIds: ['clara'],
      anchors: { clara: ANCHOR_A },
      preferred: 'nano-banana',
    })

    // A grid reference makes the model return grid frames, so only one view.
    expect(provider).toEqual({ kind: 'nano-banana', referenceUrls: [ANCHOR_A] })
  })
})

describe('multi-character shots', () => {
  it('sends one sheet view when two characters share the frame', () => {
    const provider = selectKeyframeProvider({
      characterSheet: [ANCHOR_A, ANCHOR_B, ANCHOR_A, ANCHOR_B],
      userReferenceUrl: null,
      presentCharacterIds: ['ionias', 'coffee-bot'],
      anchors: {},
      preferred: 'nano-banana',
    })

    expect(provider.kind).toBe('nano-banana')
    if (provider.kind !== 'nano-banana') return
    expect(provider.referenceUrls).toHaveLength(1)
  })
})

describe('sheet bypasses the FLUX seed', () => {
  it('uses the sheet even when no character has an anchor yet', async () => {
    const { readFileSync } = await import('node:fs')
    const source = readFileSync('server/story/shot-keyframe-orchestrator.ts', 'utf8')

    // The uploaded image is the reference; the sheet front view is only a stored
    // fallback. It is never sent as a grid and FLUX never seeds past a reference.
    expect(source).toContain('const sheet = characterSheet ?? story.characterSheet')
    expect(source).toContain('sheetFallback: sheet === null ? null : [sheet.front]')
    expect(source).not.toContain('needsSeed')
    expect(source).not.toContain('sheetUrls(sheet)')
  })
})
